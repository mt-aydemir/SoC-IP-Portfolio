#!/usr/bin/env python3
"""Generate rtl/fft_twiddle.sv, the FFT's quarter-wave twiddle ROM.

The table holds Q[i] = round(32767 * cos(2*pi*i / 1024)) for i = 0 .. 256, a
quarter of a cosine at the largest supported transform size, 1024 points.
Every twiddle of every smaller size is one of its entries, and the other
three quadrants follow from symmetry.

The ROM is generated rather than computed in the RTL because no synthesis
tool the portfolio targets evaluates $cos at elaboration, and a hand-written
table could not be checked. The cocotb suite builds its reference model from
this same formula, so a table that drifted from it fails the regression.

    python ip/dsp/fft/scripts/gen_twiddle.py            # rewrite the ROM
    python ip/dsp/fft/scripts/gen_twiddle.py --check    # fail if it differs
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

N_MAX = 1024
QUARTER = N_MAX // 4
SCALE = 32767


def table() -> list[int]:
    return [round(SCALE * math.cos(2 * math.pi * i / N_MAX)) for i in range(QUARTER + 1)]


def render() -> str:
    q = table()
    rows = "\n".join(f"      9'd{i:<3}: q = 16'sd{v};" for i, v in enumerate(q))
    return f"""//=============================================================================
// Module      : fft_twiddle
// Category    : dsp
// Description : Twiddle-factor ROM for fft: cos and sin of 2*pi*k/1024 for
//               k = 0 .. 511, in Q1.15.
//
// GENERATED by scripts/gen_twiddle.py - do not edit. The table is a quarter
// cosine, Q[i] = round(32767 * cos(2*pi*i/1024)) for i = 0 .. 256; the other
// quadrants follow from symmetry:
//
//   k <= 256 : cos = Q[k],         sin = Q[256 - k]
//   k >  256 : cos = -Q[512 - k],  sin = Q[k - 256]
//
// A transform of 2**N_LOG2 points uses every (1024 >> N_LOG2)-th entry.
//
// Copyright (c) 2026 SoC IP Portfolio Contributors
// SPDX-License-Identifier: Apache-2.0
//=============================================================================
`default_nettype none

module fft_twiddle (
    input  wire         [8:0]  k,
    output logic signed [15:0] cos_out,
    output logic signed [15:0] sin_out
);

  // One case item per table entry: this is data, not control flow, so it is
  // left out of code coverage.
  // verilator coverage_off
  function automatic logic signed [15:0] quarter(input logic [8:0] i);
    logic signed [15:0] q;
    case (i)
{rows}
      default: q = 16'sd0;
    endcase
    quarter = q;
  endfunction
  // verilator coverage_on

  always_comb begin
    if (k <= 9'd256) begin
      cos_out = quarter(k);
      sin_out = quarter(9'd256 - k);
    end else begin
      cos_out = -quarter(9'(10'd512 - 10'(k)));
      sin_out = quarter(k - 9'd256);
    end
  end

endmodule

`default_nettype wire
"""


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="fail if the ROM is stale")
    args = p.parse_args()
    target = Path(__file__).resolve().parent.parent / "rtl" / "fft_twiddle.sv"
    text = render()
    if args.check:
        if target.read_text(encoding="utf-8") != text:
            sys.stderr.write(f"{target} is stale; rerun {Path(__file__).name}\n")
            return 1
        print(f"{target.name} is up to date")
        return 0
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
