#!/usr/bin/env python3
"""Generate rtl/aes_sbox.sv and rtl/aes_inv_sbox.sv, the AES S-box ROMs.

Both tables are computed from their definition in FIPS-197 section 5.1.1:
the multiplicative inverse in GF(2**8) modulo x**8 + x**4 + x**3 + x + 1
(zero maps to zero), followed by the affine transformation

    b'[i] = b[i] ^ b[(i+4)%8] ^ b[(i+5)%8] ^ b[(i+6)%8] ^ b[(i+7)%8] ^ c[i]

with c = 0x63. The inverse S-box is the inverse permutation.

The ROMs are generated rather than typed so that they can be checked; the
cocotb model computes its own S-box from the same definition, so a table
that drifted from it fails the regression.

    python ip/crypto/aes128/scripts/gen_sbox.py            # rewrite the ROMs
    python ip/crypto/aes128/scripts/gen_sbox.py --check    # fail if they differ
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path


def gf_mul(a: int, b: int) -> int:
    r = 0
    while b:
        if b & 1:
            r ^= a
        a <<= 1
        if a & 0x100:
            a ^= 0x11B
        b >>= 1
    return r


def gf_inv(a: int) -> int:
    if a == 0:
        return 0
    r = 1
    for _ in range(254):          # a**254 = a**-1 in GF(2**8)
        r = gf_mul(r, a)
    return r


def sbox() -> list[int]:
    table = []
    for x in range(256):
        b = gf_inv(x)
        s = 0x63
        for i in range(8):
            bit = (b >> i) ^ (b >> ((i + 4) % 8)) ^ (b >> ((i + 5) % 8)) \
                ^ (b >> ((i + 6) % 8)) ^ (b >> ((i + 7) % 8))
            s ^= (bit & 1) << i
        table.append(s)
    return table


def inv_sbox() -> list[int]:
    forward = sbox()
    table = [0] * 256
    for x, y in enumerate(forward):
        table[y] = x
    return table


def module(name: str, what: str, table: list[int]) -> str:
    rows = "\n".join(f"      8'h{x:02x}: q = 8'h{v:02x};" for x, v in enumerate(table))
    return f"""// {what}
module {name} (
    input  wire  [7:0] a,
    output logic [7:0] q
);
  always_comb begin
    unique case (a)
{rows}
    endcase
  end
endmodule
"""


HEADER = """//=============================================================================
// Module      : {name}
// Category    : crypto
// Description : {desc}
//
// GENERATED by scripts/gen_sbox.py - do not edit. The table is computed
// from the FIPS-197 definition: the inverse in GF(2**8) modulo
// x**8 + x**4 + x**3 + x + 1, then the affine transformation with constant
// 0x63; the inverse S-box is the inverse permutation.
//
// Copyright (c) 2026 SoC IP Portfolio Contributors
// SPDX-License-Identifier: Apache-2.0
//=============================================================================
`default_nettype none

"""


def render(name: str) -> str:
    if name == "aes_sbox":
        desc, what, table = ("The AES S-box as a 256-entry ROM.",
                             "SubBytes for one byte (FIPS-197 figure 7)", sbox())
    else:
        desc, what, table = ("The AES inverse S-box as a 256-entry ROM.",
                             "InvSubBytes for one byte (FIPS-197 figure 14)", inv_sbox())
    return (HEADER.format(name=name, desc=desc) + module(name, what, table)
            + "\n`default_nettype wire\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a ROM file differs")
    args = parser.parse_args()
    rtl = Path(__file__).resolve().parent.parent / "rtl"
    stale = 0
    for name in ("aes_sbox", "aes_inv_sbox"):
        path, text = rtl / f"{name}.sv", render(name)
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{path} is out of date; run {Path(__file__).name}", file=sys.stderr)
                stale += 1
            else:
                print(f"{path.name} is up to date")
        else:
            path.write_text(text)
            print(f"wrote {path}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
